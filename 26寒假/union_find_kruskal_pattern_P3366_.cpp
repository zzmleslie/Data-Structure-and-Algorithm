// kruskal (贪心 + 并查集)
//贪心 -》 值小    并查集 -》 维护数据，使之不会成圈
//把输入的边存起来，然后把边按边权为关键字从小到大排序，然后遍历这些边。
//我们贪心地尽量使用边权小的边，由于要生成的是树，意味着我们不能出现环，也就是两个点之间只能有一条路径。
//所以我们可以用并查集来维护这些点，当遍历到的边中的两个点已经在同一个连通块里面，
//则这条边不能使用，否则加入这条边，将两个点合并到一个连通块。
// 包含必要的头文件
#include<iostream>      // 输入输出流
#include<cstdio>        // C风格输入输出，使用scanf/printf提高效率
#include<algorithm>     // 包含sort()函数，用于排序
using namespace std;    // 使用标准命名空间

// 定义常量
const int N = 5100;     // 最大顶点数
const int M = 2e5 + 100;// 最大边数，2e5表示200000，+100是为了留有余量

// 全局变量定义
int n, m;               // n:顶点数，m:边数
int fa[N];              // 并查集的父节点数组，fa[i]存储节点i的父节点
int cnt, sum;           // cnt:已选择的边数，sum:最小生成树的总权值

// 定义边的结构体
struct node {
    int x, y, z;        // x,y:边的两个端点，z:边的权值
} a[M];                 // 存储所有边的数组

// 比较函数：用于sort()排序
// 按照边的权值z从小到大排序（升序）
bool cmp(node a1, node a2) {
    return a1.z < a2.z; // 如果a1.z < a2.z返回true，表示a1应该排在a2前面
}

// 并查集：查找函数（带路径压缩优化）
// 作用：找到节点dx所在集合的根节点，并进行路径压缩
int set_find(int dx) {
    // 使用三元运算符：
    // 如果dx是自己的父节点（说明dx是根节点），返回dx
    // 否则递归查找dx的父节点，并更新fa[dx]为根节点（路径压缩）
    return dx == fa[dx] ? dx : fa[dx] = set_find(fa[dx]);
    
    // 等价写法：
    // if (dx == fa[dx]) {
    //     return dx;           // dx是根节点
    // } else {
    //     fa[dx] = set_find(fa[dx]);  // 路径压缩：将dx直接连接到根节点
    //     return fa[dx];       // 返回根节点
    // }
}

// 并查集：合并函数
// 作用：将节点dx和节点dy所在的两个集合合并
void set_merge(int dx, int dy) {
    int gx = set_find(dx);  // 找到dx所在集合的根节点
    int gy = set_find(dy);  // 找到dy所在集合的根节点
    
    // 如果两个节点不在同一个集合中
    if (gx != gy) {
        fa[gx] = gy;        // 合并：将gx的根节点指向gy
        // 这里将gx所在集合合并到gy所在集合，也可以反过来
    }
    // 如果gx == gy，说明dx和dy已经在同一个集合，不需要合并
}

// 主函数
int main() {
    // 输入顶点数n和边数m
    scanf("%d%d", &n, &m);
    
    // 初始化并查集：每个节点自成一个集合
    for (int i = 1; i <= n; i++) {
        fa[i] = i;          // 每个节点的父节点指向自己
    }
    
    // 输入所有的边信息
    for (int i = 1; i <= m; i++) {
        // 输入一条边：两个端点x,y和权值z
        scanf("%d%d%d", &a[i].x, &a[i].y, &a[i].z);
    }
    
    // 关键步骤1：对所有边按权值从小到大排序
    // a+1: 数组起始位置（因为边从a[1]开始存储）
    // a+m+1: 数组结束位置的下一个位置（左闭右开区间）
    // cmp: 比较函数，决定排序规则
    sort(a + 1, a + m + 1, cmp);
    
    // 关键步骤2：Kruskal算法核心 - 遍历所有已排序的边
    for (int i = 1; i <= m; i++) {
        // 检查当前边的两个端点是否在同一个连通分量中
        // 如果不在同一个集合，说明加入这条边不会形成环
        if (set_find(a[i].x) != set_find(a[i].y)) {
            // 选择这条边
            set_merge(a[i].x, a[i].y);  // 合并两个端点所在的集合
            cnt++;                      // 已选边数加1
            sum += a[i].z;              // 累加边权到总权值
            
            // 输出调试信息（可选）
            // printf("选择边: %d-%d, 权值: %d, 当前总权值: %d\n", 
            //        a[i].x, a[i].y, a[i].z, sum);
        }
        
        // 优化：如果已经选择了n-1条边，最小生成树已经完成
        // 一棵树有n个顶点，一定有n-1条边
        if (cnt == n - 1) {
            break;  // 提前结束循环
        }
    }
    
    // 输出结果
    // 判断图是否连通：如果选择的边数小于n-1，说明图不连通
    if (cnt < n - 1) {
        printf("orz");  // 输出"orz"表示图不连通，无法生成最小生成树
    } else {
        printf("%d", sum);  // 输出最小生成树的总权值
    }
    
    return 0;  // 程序正常结束
}

/*
算法执行流程总结：
1. 初始化并查集，每个顶点自成一个集合
2. 输入所有边并存储
3. 将所有边按权值从小到大排序
4. 从小到大遍历每条边：
   a. 如果边的两个端点不在同一集合（不会形成环）：
      - 选择这条边加入最小生成树
      - 合并两个端点所在的集合
      - 累加边权，计数边数
   b. 如果已选够n-1条边，结束算法
5. 输出结果：
   - 如果边数不够n-1：输出"orz"（图不连通）
   - 否则输出最小生成树总权值

时间复杂度分析：
1. 排序：O(m log m) - 主要开销
2. 遍历边：O(m)次并查集操作
3. 并查集操作（带路径压缩）：近似O(1)
4. 总时间复杂度：O(m log m)

空间复杂度分析：
1. 存储边：O(m)
2. 并查集数组：O(n)
3. 总空间复杂度：O(m + n)
*/